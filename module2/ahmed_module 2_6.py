
# ==================================
# 1. إعدادات اللعبة الأساسية
# ==================================

# إنشاء لوحة فيها 4 صفوف و4 أعمدة
# الرقم 0 يعني أن المربع فاضي
board = [[0] * 4 for i in range(4)]

# متغير لحساب نقاط اللاعب
score = 0

# رقم نستخدمه لتوليد أرقام شبه عشوائية
seed = 12345


# ==================================
# 2. دالة توليد رقم شبه عشوائي
# ==================================

# هذي الدالة تختار رقم من 0 إلى n-1
# نستخدمها عشان نختار مكان الرقم الجديد
def random_number(n):
    global seed

    # تحديث الرقم المستخدم للتوليد
    seed = (seed * 1103515245 + 12345) % 2147483648

    # إرجاع رقم ضمن العدد المطلوب
    return seed % n


# ==================================
# 3. إضافة رقم جديد إلى اللعبة
# ==================================

# هذي الدالة تضيف 2 أو 4 في مربع فاضي
def add_number():

    # قائمة نخزن فيها أماكن المربعات الفاضية
    empty = []

    # المرور على الصفوف الأربعة
    for r in range(4):

        # المرور على الأعمدة الأربعة
        for c in range(4):

            # إذا كان المربع فاضي
            if board[r][c] == 0:

                # نحفظ مكان المربع الفاضي
                empty.append((r, c))

    # إذا فيه مربعات فاضية
    if empty:

        # اختيار مربع فاضي بشكل شبه عشوائي
        r, c = empty[random_number(len(empty))]

        # إضافة 4 باحتمال 10% وإلا نضيف 2
        board[r][c] = 4 if random_number(10) == 0 else 2


# ==================================
# 4. عرض لوحة اللعبة في Terminal
# ==================================

def show_board():

    # عرض نقاط اللاعب
    print("\nScore:", score)

    # طباعة خط للفصل
    print("-" * 25)

    # المرور على كل صف في اللوحة
    for row in board:

        # المرور على كل رقم في الصف
        for number in row:

            # إذا المربع فاضي نعرض نقطة
            if number == 0:
                print(f"{'.':^6}", end="")

            # إذا فيه رقم نعرض الرقم
            else:
                print(f"{number:^6}", end="")

        # النزول لسطر جديد بعد كل صف
        print()

    # طباعة خط أسفل اللوحة
    print("-" * 25)


# ==================================
# 5. دمج الأرقام المتشابهة
# ==================================

# مثال: [2, 2, 4, 4]
# بعد الدمج: [4, 8, 0, 0]

def merge(row):

    # نستخدم score الموجود خارج الدالة
    global score

    # حذف الأصفار مؤقتاً من الصف
    numbers = [n for n in row if n != 0]

    # قائمة جديدة لتخزين الأرقام بعد الدمج
    result = []

    # نبدأ من أول رقم
    i = 0

    # نستمر حتى نخلص الأرقام
    while i < len(numbers):

        # إذا الرقم الحالي يساوي الرقم اللي بعده
        if i + 1 < len(numbers) and numbers[i] == numbers[i + 1]:

            # نجمع الرقمين عن طريق ضرب الرقم في 2
            value = numbers[i] * 2

            # نضيف الرقم الجديد للقائمة
            result.append(value)

            # نزيد نقاط اللاعب
            score += value

            # نتجاوز الرقمين لأننا دمجناهم
            i += 2

        else:

            # إذا الأرقام مختلفة نخلي الرقم مثل ما هو
            result.append(numbers[i])

            # ننتقل للرقم اللي بعده
            i += 1

    # نضيف أصفار حتى يصير طول الصف 4
    while len(result) < 4:
        result.append(0)

    # نرجع الصف بعد الدمج
    return result


# ==================================
# 6. تحريك الأرقام
# ==================================

# W = فوق
# A = يسار
# S = تحت
# D = يمين

def move(direction):

    # متغير يعرف إذا اللوحة تغيرت
    changed = False

    # نمر على الصفوف أو الأعمدة الأربعة
    for i in range(4):

        # إذا الحركة يسار أو يمين
        if direction in ["a", "d"]:

            # نحدد أماكن الصف
            positions = [(i, j) for j in range(4)]

        else:

            # إذا الحركة فوق أو تحت
            # نحدد أماكن العمود
            positions = [(j, i) for j in range(4)]

        # نعكس الترتيب للحركة يمين أو تحت
        if direction in ["d", "s"]:
            positions.reverse()

        # نحفظ الأرقام قبل الحركة
        old = [board[r][c] for r, c in positions]

        # نحرك الأرقام وندمج المتشابه
        new = merge(old)

        # نتأكد إذا صار تغيير في الصف أو العمود
        if old != new:
            changed = True

        # نرجع الأرقام الجديدة إلى اللوحة
        for j in range(4):
            r, c = positions[j]
            board[r][c] = new[j]

    # نرجع إذا صارت حركة أو لا
    return changed


# ==================================
# 7. التأكد من خسارة اللاعب
# ==================================

def game_over():

    # نفحص كل صف
    for r in range(4):

        # نفحص كل عمود
        for c in range(4):

            # إذا فيه مربع فاضي فاللعبة تستمر
            if board[r][c] == 0:
                return False

            # إذا فيه رقم مشابه تحته نقدر ندمجهم
            if r < 3 and board[r][c] == board[r + 1][c]:
                return False

            # إذا فيه رقم مشابه على يمينه
            if c < 3 and board[r][c] == board[r][c + 1]:
                return False

    # إذا ما فيه مربعات فاضية ولا دمج ممكن
    # يعني اللاعب خسر
    return True


# ==================================
# 8. بداية اللعبة
# ==================================

# إضافة أول رقمين إلى اللوحة
add_number()
add_number()


# ==================================
# 9. تشغيل اللعبة
# ==================================

# تكرار اللعبة حتى الفوز أو الخسارة أو الخروج
while True:

    # عرض اللوحة
    show_board()

    # التأكد إذا اللاعب وصل إلى 2048
    if any(2048 in row for row in board):
        print("You win!")
        break

    # التأكد إذا اللاعب خسر
    if game_over():
        print("Game Over!")
        break

    # طلب الحركة من اللاعب
    direction = input("Move (W/A/S/D) or Q to quit: ").lower()

    # إذا اللاعب اختار Q نوقف اللعبة
    if direction == "q":
        print("Goodbye!")
        break

    # التأكد أن اللاعب اختار حرف صحيح
    if direction not in ["w", "a", "s", "d"]:
        print("Invalid choice!")
        continue

    # تحريك الأرقام حسب اختيار اللاعب
    if move(direction):

        # إذا تغيرت اللوحة نضيف رقم جديد
        add_number()

    else:

        # إذا ما نقدر نحرك الأرقام
        print("No movement possible!")
